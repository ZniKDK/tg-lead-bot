def summary(data: dict) -> str:
    return (
        "Проверьте данные:\n\n"
        f"Услуга: <b>{escape(data['service'])}</b>\n"
        f"Дата и время: <b>{data['date_label']}, {data['time']}</b>\n"
        f"Имя: <b>{escape(data['name'])}</b>\n"
        f"Телефон: <b>{data['phone']}</b>"
    )


def lead_card(lead: dict) -> str:
    return (
        f"<b>Заявка №{lead['id']}</b> · {STATUSES[lead['status']]}\n"
        f"Услуга: {escape(lead['service'])}\n"
        f"Когда: {lead['visit_date']} {lead['visit_time']}\n"
        f"Имя: {escape(lead['name'])}\n"
        f"Телефон: {lead['phone']}\n"
        f"Создана: {lead['created_at']}"
    )
